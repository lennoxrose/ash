#!/bin/sh
# Writes hearth/front/src/jexplain/C/explain_data.c from the "Error codes" section of docs/MEMORY_SAFETY.md:
# one entry per "### E0101: title" heading, up to the next heading. `ashvm explain` prints these.
#   tools/gen_explain.sh > hearth/front/src/jexplain/C/explain_data.c
# hearth/front/tests/scripts/explain_check.sh fails when the committed file is out of date.
set -eu
cd "$(dirname "$0")/.."
awk '
function esc(s) { gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s); return s }
BEGIN {
    print "/* Generated by tools/gen_explain.sh from docs/MEMORY_SAFETY.md. Do not edit. */"
    print "#include \"jexplain/H/jexplain.h\""
    print ""
    print "const JExplain jexplain_table[] = {"
}
function close_entry() { if (open) { print "    },"; open = 0 } }
/^## / { close_entry(); in_sec = ($0 == "## Error codes"); next }
in_sec && /^### E[0-9][0-9][0-9][0-9]: / {
    close_entry()
    code = substr($0, 5, 5)
    title = substr($0, 12)
    printf "    { \"%s\", \"%s\",\n", code, esc(title)
    open = 1; started = 0; blank = 0
    next
}
in_sec && open {
    if ($0 == "") { if (started) blank++; next }
    for (; blank > 0; blank--) print "      \"\\n\""
    started = 1
    printf "      \"%s\\n\"\n", esc($0)
}
END { close_entry(); print "    { 0, 0, 0 }\n};" }
' docs/MEMORY_SAFETY.md
