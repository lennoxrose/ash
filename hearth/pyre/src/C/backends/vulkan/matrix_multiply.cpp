// Vulkan compute dispatch for the one kernel this backend has so far.
// Same "compiles against the real SDK, never run end-to-end" caveat as
// context.cpp -- this sandbox has no device to dispatch work to at all.
// Most VkResult checks below are omitted (matching this project's
// existing style of not writing defensive code for failures that need
// a debugging session, not a guard, to actually diagnose) -- when this
// runs for the first time on real hardware and something's wrong, run
// it with VK_LAYER_KHRONOS_validation enabled (`vulkan-validation-layers`,
// not installed by install_deps.sh since it's a debug tool, not a build
// dependency); the validation layer will name the exact call and the
// exact violated rule far more precisely than a hand-checked VkResult
// ever would.
#include "H/backends/vulkan/context.h"
#include "H/backends/vulkan/context_internal.hpp"
#include <vulkan/vulkan.h>
#include <cstring>
#include <cstdint>

