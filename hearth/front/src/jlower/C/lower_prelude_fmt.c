#include "jlower/H/jlower_internal.h"

/* String.format / String.formatted / PrintStream.printf: a runtime formatter written in the IR language, emitted
 * only when a program uses it (prune_module drops unreferenced functions). Arguments arrive in an array; a
 * double, float or char argument is wrapped as {"__fv": value, "__fk": "d" | "f" | "c"} by the lowering (lower_args_ex)
 * because the VM sees all of them as plain numbers and %s must print 3.0 / 'c' like Java.
 *
 * Supported: %d %s %S %c %b %B %f %x %X %o %n %% with the flags - 0 + space , # a width and a precision (%.2f, %.3s).
 * %f rounds half up on the shortest decimal digits of the double, like java.util.Formatter. A malformed
 * specifier or a missing argument raises IllegalArgumentException (Java: IllegalFormatException); extra
 * arguments are ignored, as in Java. */

static char *ex_ctor(const char *qname) {
    JMethod *k = find_ctor(jt_well_known(qname), 1);
    return k ? fn_name(k, "new") : (char *)"__missing_ctor";
}

void emit_prelude_fmt(JBuf *b) {
    j_buf_addf(b, "forge __fmterr(m) { raise %s(m); }\n", ex_ctor("ash.lang.IllegalArgumentException"));
    j_buf_add(b,
        "forge __fmtpad(s, w, left) {\n"
        "    given len(s) >= w { yield s; }\n"
        "    given left { yield s + repeat(\" \", w - len(s)); }\n"
        "    yield repeat(\" \", w - len(s)) + s;\n"
        "}\n"
        "forge __fmtgroup(ds) {\n"
        "    local dot = indexOf(ds, \".\");\n"
        "    local ip = ds;\n"
        "    local tail = \"\";\n"
        "    given dot >= 0 { ip = substring(ds, 0, dot); tail = substring(ds, dot, len(ds)); }\n"
        "    local out = \"\";\n"
        "    local k = len(ip);\n"
        "    during k > 3 { out = \",\" + substring(ip, k - 3, k) + out; k -= 3; }\n"
        "    yield substring(ip, 0, k) + out + tail;\n"
        "}\n"
        "forge __fmtnum(neg, digits, flags, w) {\n"
        "    local sign = \"\";\n"
        "    given neg { sign = \"-\"; }\n"
        "    given not neg and indexOf(flags, \"+\") >= 0 { sign = \"+\"; }\n"
        "    given not neg and sign == \"\" and indexOf(flags, \" \") >= 0 { sign = \" \"; }\n"
        "    given indexOf(flags, \",\") >= 0 { digits = __fmtgroup(digits); }\n"
        "    local left = indexOf(flags, \"-\") >= 0;\n"
        "    given indexOf(flags, \"0\") >= 0 and not left and len(sign) + len(digits) < w {\n"
        "        digits = repeat(\"0\", w - len(sign) - len(digits)) + digits;\n"
        "    }\n"
        "    yield __fmtpad(sign + digits, w, left);\n"
        "}\n"
        "forge __fmtplain(s) {\n"
        "    local ei = indexOf(s, \"E\");\n"
        "    given ei < 0 { ei = indexOf(s, \"e\"); }\n"
        "    given ei < 0 { yield s; }\n"
        "    local m = substring(s, 0, ei);\n"
        "    local e = num(substring(s, ei + 1, len(s)));\n"
        "    local dot = indexOf(m, \".\");\n"
        "    given dot < 0 { dot = len(m); m = m + \".\"; }\n"
        "    local digs = substring(m, 0, dot) + substring(m, dot + 1, len(m));\n"
        "    local pos = dot + e;\n"
        "    given pos <= 0 { yield \"0.\" + repeat(\"0\", 0 - pos) + digs; }\n"
        "    given pos >= len(digs) { yield digs + repeat(\"0\", pos - len(digs)) + \".0\"; }\n"
        "    yield substring(digs, 0, pos) + \".\" + substring(digs, pos, len(digs));\n"
        "}\n"
        "forge __fmtfixed(a, p) {\n"
        "    local s = __fmtplain(__dstr(a));\n"
        "    local dot = indexOf(s, \".\");\n"
        "    local ip = substring(s, 0, dot);\n"
        "    local fp = substring(s, dot + 1, len(s));\n"
        "    given len(fp) <= p {\n"
        "        given p == 0 { yield ip; }\n"
        "        yield ip + \".\" + fp + repeat(\"0\", p - len(fp));\n"
        "    }\n"
        "    local keep = ip + substring(fp, 0, p);\n"
        "    given ord(fp[p]) - 48 >= 5 { keep = __sinc(keep); }\n"
        "    given p == 0 { yield keep; }\n"
        "    local il = len(keep) - p;\n"
        "    yield substring(keep, 0, il) + \".\" + substring(keep, il, len(keep));\n"
        "}\n"
        "forge __format(f, args) {\n"
        "    local r = \"\";\n"
        "    local n = len(f);\n"
        "    local i = 0;\n"
        "    local ai = 0;\n"
        "    during i < n {\n"
        "        local rest = substring(f, i, n);\n"
        "        local j = indexOf(rest, \"%\");\n"
        "        given j < 0 { r = r + rest; i = n; stop; }\n"
        "        r = r + substring(rest, 0, j);\n"
        "        local st = i + j;\n"
        "        i = st + 1;\n"
        "        local flags = \"\";\n"
        "        during i < n and indexOf(\"-0+ ,#\", f[i]) >= 0 { flags = flags + f[i]; i += 1; }\n"
        "        local w = 0;\n"
        "        during i < n and indexOf(\"0123456789\", f[i]) >= 0 { w = w * 10 + ord(f[i]) - 48; i += 1; }\n"
        "        local p = 0 - 1;\n"
        "        given i < n and f[i] == \".\" {\n"
        "            i += 1;\n"
        "            p = 0;\n"
        "            during i < n and indexOf(\"0123456789\", f[i]) >= 0 { p = p * 10 + ord(f[i]) - 48; i += 1; }\n"
        "        }\n"
        "        given i >= n { __fmterr(\"Conversion = '%'\"); }\n"
        "        local cv = f[i];\n"
        "        i += 1;\n"
        "        local left = indexOf(flags, \"-\") >= 0;\n"
        "        given cv == \"%\" { r = r + __fmtpad(\"%\", w, left); next; }\n"
        "        given cv == \"n\" { r = r + chr(10); next; }\n"
        "        given indexOf(\"dsScbBfxXo\", cv) < 0 { __fmterr(\"Conversion = '\" + cv + \"'\"); }\n"
        "        given ai >= len(args) { __fmterr(\"Format specifier '\" + substring(f, st, i) + \"'\"); }\n"
        "        local a = args[ai];\n"
        "        ai += 1;\n"
        "        local kind = \"\";\n"
        "        given type(a) == \"map\" and has(a, \"__fk\") { kind = a[\"__fk\"]; a = a[\"__fv\"]; }\n"
        "        local ta = type(a);\n"
        "        given cv == \"s\" or cv == \"S\" {\n"
        "            local s = __str(a);\n"
        "            given kind == \"d\" { s = __dstr(a); }\n"
        "            given kind == \"f\" { s = __fstr(a); }\n"
        "            given kind == \"c\" { s = chr(a); }\n"
        "            given p >= 0 and len(s) > p { s = substring(s, 0, p); }\n"
        "            given cv == \"S\" { s = upper(s); }\n"
        "            r = r + __fmtpad(s, w, left);\n"
        "            next;\n"
        "        }\n"
        "        given cv == \"c\" {\n"
        "            local s = \"null\";\n"
        "            given ta == \"number\" { s = chr(a); }\n"
        "            given ta == \"string\" { s = a; }\n"
        "            r = r + __fmtpad(s, w, left);\n"
        "            next;\n"
        "        }\n"
        "        given cv == \"b\" or cv == \"B\" {\n"
        "            local s = \"true\";\n"
        "            given ta == \"none\" or (ta == \"boolean\" and not a) { s = \"false\"; }\n"
        "            given cv == \"B\" { s = upper(s); }\n"
        "            r = r + __fmtpad(s, w, left);\n"
        "            next;\n"
        "        }\n"
        "        given ta == \"none\" { r = r + __fmtpad(\"null\", w, left); next; }\n"
        "        given cv == \"d\" {\n"
        "            local s = __str(a);\n"
        "            local neg = substring(s, 0, 1) == \"-\";\n"
        "            given neg { s = substring(s, 1, len(s)); }\n"
        "            r = r + __fmtnum(neg, s, flags, w);\n"
        "            next;\n"
        "        }\n"
        "        given cv == \"f\" {\n"
        "            local x = a;\n"
        "            given ta == \"map\" { x = num(__lstr(a)); }\n"
        "            given x != x { r = r + __fmtpad(\"NaN\", w, left); next; }\n"
        "            given x != 0 and x * 2 == x {\n"
        "                local inf = x > 0 ? \"Infinity\" : \"-Infinity\";\n"
        "                given x > 0 and indexOf(flags, \"+\") >= 0 { inf = \"+Infinity\"; }\n"
        "                r = r + __fmtpad(inf, w, left);\n"
        "                next;\n"
        "            }\n"
        "            local neg = x < 0;\n"
        "            local mag = neg ? 0 - x : x;\n"
        "            r = r + __fmtnum(neg, __fmtfixed(mag, p < 0 ? 6 : p), flags, w);\n"
        "            next;\n"
        "        }\n"
        "        local base = cv == \"o\" ? 8 : 16;\n"
        "        local v = a;\n"
        "        given ta == \"map\" { v = num(__lstr(a)); }\n"
        "        given v < 0 { v = v + 4294967296; }\n"
        "        local s = \"\";\n"
        "        local dg = \"0123456789abcdef\";\n"
        "        given v == 0 { s = \"0\"; }\n"
        "        during v > 0 { s = dg[v % base] + s; v = floor(v / base); }\n"
        "        given cv == \"X\" { s = upper(s); }\n"
        "        given indexOf(flags, \"#\") >= 0 { s = (cv == \"o\" ? \"0\" : (cv == \"X\" ? \"0X\" : \"0x\")) + s; }\n"
        "        r = r + __fmtnum(no, s, flags, w);\n"
        "    }\n"
        "    yield r;\n"
        "}\n");
}
