#include "jlower/H/jlower_internal.h"

/* Exact 64-bit `long` support (used with --wrap-int). A long is a plain number while it fits in
 * +-2^53 and a map {"__L": 1, "hi": signed 32 bits, "lo": unsigned 32 bits} beyond that, so the
 * common case keeps the VM's fast numeric path. Generated from the reviewed Ash source: every
 * operation normalises back to a number when the result fits. */

static char *ex_ctor(const char *qname) {
    JMethod *k = find_ctor(jt_well_known(qname), 1);
    return k ? fn_name(k, "new") : (char *)"__missing_ctor";
}

void emit_prelude_long(JBuf *b) {
    j_buf_addf(b, "forge __arith(m) { raise %s(m); }\n", ex_ctor("ash.lang.ArithmeticException"));
    j_buf_addf(b, "forge __parsex(m) { raise %s(m); }\n", ex_ctor("ash.lang.ParseException"));
    j_buf_add(b,
        "forge __L2(x) {\n"
        "    given type(x) == \"map\" { yield [x[\"hi\"], x[\"lo\"]]; }\n"
        "    local hi = floor(x / 4294967296);\n"
        "    yield [hi, x - hi * 4294967296];\n"
        "}\n"
        "forge __LN(hi, lo) {\n"
        "    local h = __wg(hi);\n"
        "    given h >= 0 - 2097152 and h < 2097152 { yield h * 4294967296 + lo; }\n"
        "    yield {\"__L\": 1, \"hi\": h, \"lo\": lo};\n"
        "}\n"
        "forge __lisL(x) { yield type(x) == \"map\"; }\n"
        "forge __lneg(a) {\n"
        "    given type(a) == \"number\" { yield 0 - a; }\n"
        "    local x = __L2(a);\n"
        "    local lo = 4294967296 - x[1];\n"
        "    local hi = 0 - x[0] - 1;\n"
        "    given lo == 4294967296 { lo = 0; hi += 1; }\n"
        "    yield __LN(hi, lo);\n"
        "}\n"
        "forge __ladd(a, b) {\n"
        "    given type(a) == \"number\" and type(b) == \"number\" {\n"
        "        local r = a + b;\n"
        "        given r > 0 - 9007199254740992 and r < 9007199254740992 { yield r; }\n"
        "    }\n"
        "    local x = __L2(a);\n"
        "    local y = __L2(b);\n"
        "    local lo = x[1] + y[1];\n"
        "    local c = 0;\n"
        "    given lo >= 4294967296 { lo -= 4294967296; c = 1; }\n"
        "    yield __LN(x[0] + y[0] + c, lo);\n"
        "}\n"
        "forge __lsub(a, b) {\n"
        "    given type(a) == \"number\" and type(b) == \"number\" {\n"
        "        local r = a - b;\n"
        "        given r > 0 - 9007199254740992 and r < 9007199254740992 { yield r; }\n"
        "    }\n"
        "    yield __ladd(a, __lneg(b));\n"
        "}\n"
        "forge __lmul(a, b) {\n"
        "    given type(a) == \"number\" and type(b) == \"number\" {\n"
        "        local r = a * b;\n"
        "        given r > 0 - 9007199254740992 and r < 9007199254740992 { yield r; }\n"
        "    }\n"
        "    local x = __L2(a);\n"
        "    local y = __L2(b);\n"
        "    local xh = x[0];\n"
        "    given xh < 0 { xh += 4294967296; }\n"
        "    local yh = y[0];\n"
        "    given yh < 0 { yh += 4294967296; }\n"
        "    local a0 = x[1] % 65536;\n"
        "    local a1 = floor(x[1] / 65536);\n"
        "    local a2 = xh % 65536;\n"
        "    local a3 = floor(xh / 65536);\n"
        "    local b0 = y[1] % 65536;\n"
        "    local b1 = floor(y[1] / 65536);\n"
        "    local b2 = yh % 65536;\n"
        "    local b3 = floor(yh / 65536);\n"
        "    local t0 = a0 * b0;\n"
        "    local c0 = floor(t0 / 65536);\n"
        "    local d0 = t0 - c0 * 65536;\n"
        "    local t1 = a0 * b1 + a1 * b0 + c0;\n"
        "    local c1 = floor(t1 / 65536);\n"
        "    local d1 = t1 - c1 * 65536;\n"
        "    local t2 = a0 * b2 + a1 * b1 + a2 * b0 + c1;\n"
        "    local c2 = floor(t2 / 65536);\n"
        "    local d2 = t2 - c2 * 65536;\n"
        "    local t3 = a0 * b3 + a1 * b2 + a2 * b1 + a3 * b0 + c2;\n"
        "    local d3 = t3 % 65536;\n"
        "    local hu = d2 + d3 * 65536;\n"
        "    given hu >= 2147483648 { hu -= 4294967296; }\n"
        "    yield __LN(hu, d0 + d1 * 65536);\n"
        "}\n"
        "forge __lcmp(a, b) {\n"
        "    given type(a) == \"number\" and type(b) == \"number\" {\n"
        "        given a < b { yield -1; }\n"
        "        given a > b { yield 1; }\n"
        "        yield 0;\n"
        "    }\n"
        "    local x = __L2(a);\n"
        "    local y = __L2(b);\n"
        "    given x[0] < y[0] { yield -1; }\n"
        "    given x[0] > y[0] { yield 1; }\n"
        "    given x[1] < y[1] { yield -1; }\n"
        "    given x[1] > y[1] { yield 1; }\n"
        "    yield 0;\n"
        "}\n"
        "forge __leq(a, b) {\n"
        "    given type(a) == \"number\" and type(b) == \"number\" { yield a == b; }\n"
        "    yield __lcmp(a, b) == 0;\n"
        "}\n"
        "forge __lmag(a) {\n"
        "    local neg = __lcmp(a, 0) < 0;\n"
        "    local m = a;\n"
        "    given neg { m = __lneg(a); }\n"
        "    local x = __L2(m);\n"
        "    local hu = x[0];\n"
        "    given hu < 0 { hu += 4294967296; }\n"
        "    yield [hu, x[1], neg];\n"
        "}\n"
        "forge __lfrommag(hu, lo, neg) {\n"
        "    local h = hu;\n"
        "    given h >= 2147483648 { h -= 4294967296; }\n"
        "    local v = __LN(h, lo);\n"
        "    given neg { yield __lneg(v); }\n"
        "    yield v;\n"
        "}\n"
        "forge __ldivu(nh, nl, dh, dl) {\n"
        "    local qh = 0;\n"
        "    local ql = 0;\n"
        "    local rh = 0;\n"
        "    local rl = 0;\n"
        "    local i = 63;\n"
        "    during i >= 0 {\n"
        "        rh = rh * 2 + floor(rl / 2147483648);\n"
        "        rl = (rl % 2147483648) * 2;\n"
        "        local bit = 0;\n"
        "        given i >= 32 { bit = floor(nh / __p2(i - 32)) % 2; } otherwise { bit = floor(nl / __p2(i)) % 2; }\n"
        "        rl += bit;\n"
        "        given rh > dh or (rh == dh and rl >= dl) {\n"
        "            rl -= dl;\n"
        "            given rl < 0 { rl += 4294967296; rh -= 1; }\n"
        "            rh -= dh;\n"
        "            given i >= 32 { qh += __p2(i - 32); } otherwise { ql += __p2(i); }\n"
        "        }\n"
        "        i -= 1;\n"
        "    }\n"
        "    yield [qh, ql, rh, rl];\n"
        "}\n"
        "forge __p2(n) { local r = 1; local i = 0; during i < n { r = r * 2; i += 1; } yield r; }\n"
        "forge __ldiv(a, b) {\n"
        "    given __leq(b, 0) { __arith(\"/ by zero\"); }\n"
        "    given type(a) == \"number\" and type(b) == \"number\" {\n"
        "        local aa = a;\n"
        "        local bb = b;\n"
        "        given aa < 0 { aa = 0 - aa; }\n"
        "        given bb < 0 { bb = 0 - bb; }\n"
        "        local q = floor(aa / bb);\n"
        "        local r = aa - q * bb;\n"
        "        during r < 0 { q -= 1; r += bb; }\n"
        "        during r >= bb { q += 1; r -= bb; }\n"
        "        given q == 0 { yield 0; }\n"
        "        given ((a < 0) != (b < 0)) { yield 0 - q; }\n"
        "        yield q;\n"
        "    }\n"
        "    local x = __lmag(a);\n"
        "    local y = __lmag(b);\n"
        "    local qr = __ldivu(x[0], x[1], y[0], y[1]);\n"
        "    yield __lfrommag(qr[0], qr[1], x[2] != y[2]);\n"
        "}\n"
        "forge __lrem(a, b) { yield __lsub(a, __lmul(__ldiv(a, b), b)); }\n"
        "forge __lshl(a, n) {\n"
        "    local s = n % 64;\n"
        "    given s == 0 { yield a; }\n"
        "    given type(a) == \"number\" {\n"
        "        local r = a * __p2(s);\n"
        "        given r > 0 - 9007199254740992 and r < 9007199254740992 { yield r; }\n"
        "    }\n"
        "    local x = __L2(a);\n"
        "    local hu = x[0];\n"
        "    given hu < 0 { hu += 4294967296; }\n"
        "    local lo = x[1];\n"
        "    local nh = 0;\n"
        "    local nl = 0;\n"
        "    given s >= 32 {\n"
        "        local k = s - 32;\n"
        "        nh = (lo % __p2(32 - k)) * __p2(k);\n"
        "        given k == 0 { nh = lo; }\n"
        "        nl = 0;\n"
        "    } otherwise {\n"
        "        local keep = __p2(32 - s);\n"
        "        nl = (lo % keep) * __p2(s);\n"
        "        nh = (hu % keep) * __p2(s) + floor(lo / keep);\n"
        "    }\n"
        "    given nh >= 2147483648 { nh -= 4294967296; }\n"
        "    yield __LN(nh, nl);\n"
        "}\n"
        "forge __lshr(a, n) {\n"
        "    local s = n % 64;\n"
        "    given s == 0 { yield a; }\n"
        "    given type(a) == \"number\" { yield floor(a / __p2(s)); }\n"
        "    local x = __L2(a);\n"
        "    local hi = x[0];\n"
        "    local lo = x[1];\n"
        "    local hu = hi;\n"
        "    given hu < 0 { hu += 4294967296; }\n"
        "    local nh = 0;\n"
        "    local nl = 0;\n"
        "    given s >= 32 {\n"
        "        nl = floor(hi / __p2(s - 32));\n"
        "        given nl < 0 { nl += 4294967296; }\n"
        "        nh = hi < 0 ? -1 : 0;\n"
        "    } otherwise {\n"
        "        nl = (hu % __p2(s)) * __p2(32 - s) + floor(lo / __p2(s));\n"
        "        nh = floor(hi / __p2(s));\n"
        "    }\n"
        "    yield __LN(nh, nl);\n"
        "}\n"
        "forge __lushr(a, n) {\n"
        "    local s = n % 64;\n"
        "    given s == 0 { yield a; }\n"
        "    given __lcmp(a, 0) >= 0 { yield __lshr(a, s); }\n"
        "    local x = __L2(a);\n"
        "    local hu = x[0] + 4294967296;\n"
        "    local lo = x[1];\n"
        "    local nh = 0;\n"
        "    local nl = 0;\n"
        "    given s >= 32 {\n"
        "        nl = floor(hu / __p2(s - 32));\n"
        "        nh = 0;\n"
        "    } otherwise {\n"
        "        nl = (hu % __p2(s)) * __p2(32 - s) + floor(lo / __p2(s));\n"
        "        nh = floor(hu / __p2(s));\n"
        "    }\n"
        "    yield __LN(nh, nl);\n"
        "}\n"
        "forge __lbit(a, b, op) {\n"
        "    local x = __L2(a);\n"
        "    local y = __L2(b);\n"
        "    local xh = x[0];\n"
        "    local yh = y[0];\n"
        "    given xh < 0 { xh += 4294967296; }\n"
        "    given yh < 0 { yh += 4294967296; }\n"
        "    local h = 0;\n"
        "    local l = 0;\n"
        "    given op == 0 { h = xh & yh; l = x[1] & y[1]; }\n"
        "    given op == 1 { h = xh | yh; l = x[1] | y[1]; }\n"
        "    given op == 2 { h = xh ^ yh; l = x[1] ^ y[1]; }\n"
        "    given h >= 2147483648 { h -= 4294967296; }\n"
        "    yield __LN(h, l);\n"
        "}\n"
        "forge __land(a, b) { yield __lbit(a, b, 0); }\n"
        "forge __lor(a, b) { yield __lbit(a, b, 1); }\n"
        "forge __lxor(a, b) { yield __lbit(a, b, 2); }\n"
        "forge __l2i(x) {\n"
        "    given type(x) == \"number\" { yield __wg(x); }\n"
        "    local lo = x[\"lo\"];\n"
        "    given lo >= 2147483648 { yield lo - 4294967296; }\n"
        "    yield lo;\n"
        "}\n"
        "forge __l2d(x) {\n"
        "    given type(x) == \"number\" { yield x; }\n"
        "    yield x[\"hi\"] * 4294967296 + x[\"lo\"];\n"
        "}\n"
        "forge __d2l(x) {\n"
        "    given x != x { yield 0; }\n"
        "    given x >= 9223372036854775807 { yield {\"__L\": 1, \"hi\": 2147483647, \"lo\": 4294967295}; }\n"
        "    given x <= 0 - 9223372036854775807 { yield {\"__L\": 1, \"hi\": -2147483648, \"lo\": 0}; }\n"
        "    local t = __trunc(x);\n"
        "    given t > 0 - 9007199254740992 and t < 9007199254740992 { yield t; }\n"
        "    local hi = floor(t / 4294967296);\n"
        "    yield __LN(hi, t - hi * 4294967296);\n"
        "}\n"
        "forge __lstr(x) {\n"
        "    given type(x) == \"number\" and x > 0 - 1000000000000000 and x < 1000000000000000 { yield str(x); }\n"
        "    local m = __lmag(x);\n"
        "    local limbs = [floor(m[0] / 65536), m[0] % 65536, floor(m[1] / 65536), m[1] % 65536];\n"
        "    local out = \"\";\n"
        "    local more = yes;\n"
        "    during more {\n"
        "        local rem = 0;\n"
        "        local i = 0;\n"
        "        during i < 4 {\n"
        "            local cur = rem * 65536 + limbs[i];\n"
        "            limbs[i] = floor(cur / 1000000000);\n"
        "            rem = cur - limbs[i] * 1000000000;\n"
        "            i += 1;\n"
        "        }\n"
        "        more = limbs[0] > 0 or limbs[1] > 0 or limbs[2] > 0 or limbs[3] > 0;\n"
        "        local part = str(rem);\n"
        "        given more { during len(part) < 9 { part = \"0\" + part; } }\n"
        "        out = part + out;\n"
        "    }\n"
        "    given m[2] { yield \"-\" + out; }\n"
        "    yield out;\n"
        "}\n"
        "forge __lparse(s) {\n"
        "    local t = trim(s);\n"
        "    local neg = no;\n"
        "    local i = 0;\n"
        "    given len(t) > 0 and t[0] == \"-\" { neg = yes; i = 1; }\n"
        "    given i >= len(t) { __parsex(\"not a long: \" + s); }\n"
        "    local acc = 0;\n"
        "    during i < len(t) {\n"
        "        local c = ord(t[i]);\n"
        "        given c < 48 or c > 57 { __parsex(\"not a long: \" + s); }\n"
        "        acc = __ladd(__lmul(acc, 10), c - 48);\n"
        "        i += 1;\n"
        "    }\n"
        "    given neg { yield __lneg(acc); }\n"
        "    yield acc;\n"
        "}\n"
    );
}
